export type ProductCategory =
  | "Peshawari Sandal"
  | "Formal Shoes"
  | "Casual Shoes"
  | "Loafers"
  | "Leather Jacket"
  | "Ladies Footwear";

export interface Product {
  id: string;
  name: string;
  slug: string;
  description: string;
  price: number;
  originalPrice?: number;
  image: string;
  category: ProductCategory;
  sizes: string[];
  colors?: string[];
  /** Shown as a pill overlay on the product card, e.g. "Last Pair". */
  badge?: string;
  featured?: boolean;
}

// ============================================================================
// Helpers
// ============================================================================

export const slugify = (name: string): string =>
  name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

export const formatPrice = (price: number): string =>
  `Rs.${price.toLocaleString("en-PK")}`;

export const discountPercent = (price: number, originalPrice?: number): number =>
  originalPrice
    ? Math.round(((originalPrice - price) / originalPrice) * 100)
    : 0;

const FOOTWEAR_SIZES = ["40", "41", "42", "43", "44", "45"];
const LADIES_SIZES = ["36", "37", "38", "39", "40"];
const APPAREL_SIZES = ["S", "M", "L", "XL"];

const DEFAULT_SIZES: Record<ProductCategory, string[]> = {
  "Peshawari Sandal": FOOTWEAR_SIZES,
  "Formal Shoes": FOOTWEAR_SIZES,
  "Casual Shoes": FOOTWEAR_SIZES,
  "Loafers": FOOTWEAR_SIZES,
  "Leather Jacket": APPAREL_SIZES,
  "Ladies Footwear": LADIES_SIZES,
};

const describe = (name: string, category: ProductCategory): string => {
  if (category === "Leather Jacket") {
    return `${name} — premium genuine leather with expert craftsmanship. A timeless statement piece built for style and durability.`;
  }
  if (category === "Ladies Footwear") {
    return `${name} — stylish and comfortable, designed for every occasion. Crafted with care by Paizaar.`;
  }
  return `${name} — premium quality ${category.toLowerCase()} by Paizaar. Crafted from fine materials for style, comfort and long-lasting wear.`;
};

const make = (
  id: string,
  name: string,
  category: ProductCategory,
  price: number,
  image: string,
  extra: Partial<Product> = {},
): Product => ({
  id,
  name,
  slug: slugify(name),
  description: extra.description ?? describe(name, category),
  price,
  image,
  category,
  sizes: DEFAULT_SIZES[category],
  ...extra,
});

