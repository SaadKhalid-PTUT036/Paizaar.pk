// Products shown on the homepage.
export const FEATURED_PRODUCT_IDS = ["fs1", "lf2", "cs5", "fs3"];

// ============================================================================
// Catalog queries
// ============================================================================

export const getProductById = (id?: string): Product | undefined =>
  allProducts.find((p) => p.id === id);

export const getProductBySlug = (slug?: string): Product | undefined =>
  allProducts.find((p) => p.slug === slug);

export const getProductsByCategory = (category: ProductCategory): Product[] =>
  shoes.filter((p) => p.category === category);

export const getLastPairOffers = (): Product[] =>
  lastPairOffers.filter((p) => p.badge === "Last Pair");

export const getFeaturedProducts = (count = 4): Product[] => {
  const featured = FEATURED_PRODUCT_IDS.map((id) => getProductById(id)).filter(
    (p): p is Product => Boolean(p),
  );
  if (featured.length >= count) return featured.slice(0, count);
  // Fallback: fill from regular catalog if any featured id ever disappears.
  return [...featured, ...shoes.filter((p) => !featured.includes(p))].slice(0, count);
};

export const getRelatedProducts = (product: Product, count = 4): Product[] => {
  const sameCategory = shoes.filter((p) => p.id !== product.id && p.category === product.category);
  const others = shoes.filter((p) => p.id !== product.id && p.category !== product.category);
  return [...sameCategory, ...others].slice(0, count);
};

export const searchProducts = (query: string): Product[] => {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return allProducts.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q) ||
      p.description.toLowerCase().includes(q),
  );
};